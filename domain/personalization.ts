export const PINNABLE_KINDS = ["stock", "portfolio", "view", "goal", "screen"] as const
export type PinnableKind = (typeof PINNABLE_KINDS)[number]

export type PinnedItem = {
  kind: PinnableKind
  /** A symbol key, a uuid — whatever addresses the thing. Never a figure. */
  ref: string
  label: string
}

export const MAX_PINNED = 12
export const MAX_RECENT = 8

export function togglePin(
  current: readonly PinnedItem[],
  item: PinnedItem,
): { items: PinnedItem[]; rejected: "LIMIT" | null } {
  const existing = current.findIndex((p) => p.kind === item.kind && p.ref === item.ref)
  if (existing !== -1) return { items: current.filter((_, i) => i !== existing), rejected: null }
  if (current.length >= MAX_PINNED) return { items: [...current], rejected: "LIMIT" }
  return { items: [...current, item], rejected: null }
}

export function isPinned(current: readonly PinnedItem[], kind: PinnableKind, ref: string): boolean {
  return current.some((p) => p.kind === kind && p.ref === ref)
}

/**
 * Most recent first, deduplicated, bounded.
 *
 * A bounded list rather than a history: eight entries is enough to get back to what you were just
 * looking at, and it is deliberately too short to reconstruct what somebody has been researching.
 * See the privacy note in `docs/personalization.md`.
 */
export function recordRecent(
  current: readonly PinnedItem[],
  item: PinnedItem,
  max = MAX_RECENT,
): PinnedItem[] {
  const withoutDuplicate = current.filter((p) => !(p.kind === item.kind && p.ref === item.ref))
  return [item, ...withoutDuplicate].slice(0, max)
}

