/**
 * Reconciles a stored layout with the registry.
 *
 * Three things can be wrong with a layout read from the database, and all three are normal rather
 * than exceptional: a widget was **added** in a release after it was saved, a widget was
 * **removed**, or the row is empty because the user has never customised anything. So this is not
 * validation — it is the function that makes a stored layout mean something under a registry that
 * has since changed.
 *
 * A widget the user has never seen is appended in its default visibility, never silently switched
 * on at the top where it would displace what they arranged.
 */
export function resolveLayout(stored: readonly WidgetPlacement[] | null | undefined): WidgetPlacement[] {
  if (!stored || stored.length === 0) return DEFAULT_LAYOUT.map((w) => ({ ...w }))

  const known = new Set<WidgetId>()
  const resolved: WidgetPlacement[] = []

  for (const placement of stored) {
    // A widget that no longer exists is dropped rather than rendered as a blank card.
    if (!(placement.id in WIDGET_REGISTRY) || known.has(placement.id)) continue
    known.add(placement.id)
    resolved.push({
      id: placement.id,
      // A required widget is visible whatever the stored row says — including a row written before
      // it became required.
      visible: WIDGET_REGISTRY[placement.id].required ? true : placement.visible,
    })
  }

  for (const fallback of DEFAULT_LAYOUT) {
    if (!known.has(fallback.id)) resolved.push({ ...fallback })
  }

  return resolved
}

/** The widgets to render, in order. */
export function visibleWidgets(layout: readonly WidgetPlacement[]): WidgetId[] {
  return layout.filter((w) => w.visible).map((w) => w.id)
}

export function toggleWidget(
  layout: readonly WidgetPlacement[],
  id: WidgetId,
  visible: boolean,
): WidgetPlacement[] {
  return layout.map((w) =>
    // Hiding a required widget is a no-op rather than an error: the control is not offered, and a
    // request that asks anyway simply does not change anything.
    w.id === id && !WIDGET_REGISTRY[id].required ? { ...w, visible } : { ...w },
  )
}

/**
 * Moves a widget one place up or down.
 *
 * The keyboard- and touch-accessible half of reordering, and the only half that is *required*:
 * drag-and-drop is an enhancement on a pointer device, but "move up" works with a keyboard, with a
 * screen reader and with a thumb. See `docs/personalization.md`.
 */
export function moveWidget(
  layout: readonly WidgetPlacement[],
  id: WidgetId,
  direction: "up" | "down",
): WidgetPlacement[] {
  const index = layout.findIndex((w) => w.id === id)
  if (index === -1) return layout.map((w) => ({ ...w }))

  const target = direction === "up" ? index - 1 : index + 1
  if (target < 0 || target >= layout.length) return layout.map((w) => ({ ...w }))

  const next = layout.map((w) => ({ ...w }))
  ;[next[index], next[target]] = [next[target], next[index]]
  return next
}

/** Reorders to an explicit sequence — what a drag-and-drop gesture produces. */
export function reorderWidgets(
  layout: readonly WidgetPlacement[],
  order: readonly WidgetId[],
): WidgetPlacement[] {
  const byId = new Map(layout.map((w) => [w.id, w]))
  const next: WidgetPlacement[] = []
  for (const id of order) {
    const found = byId.get(id)
    if (found && !next.some((w) => w.id === id)) {
      next.push({ ...found })
      byId.delete(id)
    }
  }
  // Anything the caller did not mention keeps its relative order at the end, so a partial order is
  // a safe request rather than a way to lose widgets.
  for (const remaining of layout) if (byId.has(remaining.id)) next.push({ ...remaining })
  return next
}

