/**
 * Personalization: what a page shows, in what order, and under what label.
 *
 * The boundary this module sits on is the same one phase 10 drew for journals and phase 13 drew for
 * sharing, and it runs one way:
 *
 *   **A preference decides what is displayed. It can never decide what is calculated.**
 *
 * There is no figure in this file. A widget is an id and a position; a metric is a *pointer* to a
 * number the analytics engine already computed; a saved view is a filter and a sort. Delete every
 * preference a user has and their holdings, cost basis and P&L are byte-identical —
 * `personalization-boundary.test.ts` asserts exactly that, and reads this file's source to keep it
 * free of anything that could reach a database or a network.
 *
 * Pure: no React, no Supabase, no fetch, no framework import.
 */

