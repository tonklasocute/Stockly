/** What a view is applied to. Deliberately narrow: no cost basis, no transaction, no note. */
export type ViewRow = {
  symbol: string
  market: string
  quantity: number
  marketValue: number | null
  weight: number | null
  unrealizedPnl: number
  returnPct: number
  sector: string | null
  tags: readonly string[]
}

/**
 * Whether one row passes one filter.
 *
 * The numeric comparisons return **false for a null**, which is the important case: a holding whose
 * weight could not be computed because no exchange rate reached the base currency is not "a holding
 * with a weight of zero". It is excluded from a `weight > 10` filter and from a `weight < 10` one,
 * because the honest answer to both is that it is unknown.
 */
export function matchesViewFilter(row: ViewRow, filter: ViewFilter): boolean {
  switch (filter.field) {
    case "tag": {
      const wanted = String(filter.value).toLowerCase()
      const has = row.tags.some((tag) => tag.toLowerCase() === wanted)
      return filter.operator === "isNot" ? !has : has
    }
    case "market": {
      const matches = row.market === String(filter.value)
      return filter.operator === "isNot" ? !matches : matches
    }
    case "weight":
      return compare(row.weight, filter)
    case "returnPct":
      return compare(row.returnPct, filter)
    case "unrealizedPnl":
      return compare(row.unrealizedPnl, filter)
  }
}

function compare(value: number | null, filter: ViewFilter): boolean {
  if (value === null || !Number.isFinite(value)) return false
  const target = Number(filter.value)
  if (!Number.isFinite(target)) return false
  switch (filter.operator) {
    case "gt":
      return value > target
    case "lt":
      return value < target
    case "is":
      return value === target
    case "isNot":
      return value !== target
  }
}

/**
 * Applies a saved view to a set of rows: filter, then sort, then group.
 *
 * Pure and total — it reorders and partitions rows and never alters one. A row's `marketValue` is
 * the same object property it was before; a view cannot change a number, only decide whether it is
 * on screen.
 */
export function applyView(
  rows: readonly ViewRow[],
  config: ViewConfig,
): { groups: { key: string; label: string; rows: ViewRow[] }[]; total: number } {
  const filtered = rows.filter((row) => config.filters.every((filter) => matchesViewFilter(row, filter)))
  const sorted = [...filtered].sort((a, b) => compareRows(a, b, config))

  if (config.groupBy === "none") {
    return { groups: [{ key: "all", label: "All holdings", rows: sorted }], total: sorted.length }
  }

  const buckets = new Map<string, ViewRow[]>()
  for (const row of sorted) {
    for (const key of groupKeys(row, config.groupBy)) {
      const bucket = buckets.get(key)
      if (bucket) bucket.push(row)
      else buckets.set(key, [row])
    }
  }

  const groups = [...buckets.entries()]
    .map(([key, groupRows]) => ({ key, label: key, rows: groupRows }))
    // "Ungrouped" always last, whatever it sorts as alphabetically: it is the residue, not a group.
    .sort((a, b) =>
      a.key === UNGROUPED ? 1 : b.key === UNGROUPED ? -1 : a.key.localeCompare(b.key),
    )

  return { groups, total: sorted.length }
}

/** The bucket for a row that the grouping cannot place. Never omitted, never guessed at. */
export const UNGROUPED = "Ungrouped"

/**
 * A row can belong to several groups when grouping by tag — a position tagged "Growth" and "Core"
 * appears under both, which is what a tag means. Every other grouping yields exactly one key.
 */
function groupKeys(row: ViewRow, grouping: Grouping): string[] {
  switch (grouping) {
    case "none":
      return ["all"]
    case "market":
      return [row.market]
    case "sector":
      // Never inferred from the symbol. A provider that returned no sector means the sector is
      // unknown, and saying so is the only honest option.
      return [row.sector ?? UNGROUPED]
    case "tag":
      return row.tags.length > 0 ? [...row.tags] : [UNGROUPED]
  }
}

function compareRows(a: ViewRow, b: ViewRow, config: ViewConfig): number {
  const direction = config.sortDirection === "asc" ? 1 : -1
  const left = sortValue(a, config.sortBy)
  const right = sortValue(b, config.sortBy)

  // Nulls sort last in both directions. A holding with no computable weight has not got the
  // smallest weight — it has an unknown one, and burying it at the bottom is less misleading than
  // putting it at either extreme.
  if (left === null && right === null) return a.symbol.localeCompare(b.symbol)
  if (left === null) return 1
  if (right === null) return -1

  if (typeof left === "string" && typeof right === "string") {
    return left.localeCompare(right) * direction
  }
  return ((left as number) - (right as number)) * direction
}

function sortValue(row: ViewRow, column: ViewColumn): string | number | null {
  switch (column) {
    case "symbol":
      return row.symbol
    case "market":
      return row.market
    case "quantity":
      return row.quantity
    case "marketValue":
      return row.marketValue
    case "weight":
      return row.weight
    case "unrealizedPnl":
      return row.unrealizedPnl
    case "returnPct":
      return row.returnPct
    // Columns a view can display but not sort by yet. Falls back to the symbol rather than
    // producing an arbitrary order that looks meaningful.
    default:
      return row.symbol
  }
}

